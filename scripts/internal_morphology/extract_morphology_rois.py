def build_extraction_summary(
    extraction_manifest: pd.DataFrame,
    failed: pd.DataFrame,
) -> pd.DataFrame:
    rows = []

    strata = sorted(
        set(
            extraction_manifest[
                "sampling_stratum"
            ].dropna().astype(
                str
            )
        )
        | set(
            failed[
                "sampling_stratum"
            ].dropna().astype(
                str
            )
        )
    )

    for stratum in strata:
        success_group = (
            extraction_manifest.loc[
                extraction_manifest[
                    "sampling_stratum"
                ] == stratum
            ]
        )

        failed_group = (
            failed.loc[
                failed[
                    "sampling_stratum"
                ] == stratum
            ]
        )

        rows.append({
            "sampling_stratum": (
                stratum
            ),
            "n_successful": int(
                len(
                    success_group
                )
            ),
            "n_failed": int(
                len(
                    failed_group
                )
            ),
            "n_patients_successful": int(
                success_group[
                    "patient_id"
                ].nunique()
            )
            if not success_group.empty
            else 0,
            "n_slides_successful": int(
                success_group[
                    "prefix"
                ].nunique()
            )
            if not success_group.empty
            else 0,
        })

    return pd.DataFrame(
        rows
    )


