def normalize_name(
    value: str,
) -> str:
    stem = Path(
        str(value)
    ).stem.lower()

    return re.sub(
        r"[^a-z0-9]",
        "",
        stem,
    )


def build_file_map(
    directories,
) -> Dict[str, Path]:
    mapping: Dict[str, Path] = {}

    for directory in directories:
        if not directory.exists():
            continue

        for path in sorted(
            directory.iterdir()
        ):
            if (
                path.is_file()
                and path.suffix.lower()
                in ALLOWED_WSI_SUFFIXES
            ):
                mapping[
                    normalize_name(
                        path.name
                    )
                ] = path

    return mapping


def find_file_by_prefix(
    prefix: str,
    file_map: Dict[str, Path],
) -> Optional[Path]:
    key = normalize_name(
        prefix
    )

    if key in file_map:
        return file_map[
            key
        ]

    candidates = [
        path
        for normalized, path
        in file_map.items()
        if (
            key in normalized
            or normalized in key
        )
    ]

    if len(
        candidates
    ) == 1:
        return candidates[
            0
        ]

    if len(
        candidates
    ) > 1:
        candidates = sorted(
            candidates,
            key=lambda path: abs(
                len(
                    normalize_name(
                        path.name
                    )
                )
                - len(
                    key
                )
            ),
        )

        return candidates[
            0
        ]

    return None


def load_json(
    path: Path,
) -> dict:
    with path.open(
        "r",
        encoding="utf-8",
    ) as file:
        return json.load(
            file
        )


def resolve_wsi_path(
    row: pd.Series,
    wsi_map: Dict[str, Path],
) -> Optional[Path]:
    meta_path = Path(
        str(
            row["meta_path"]
        )
    )

    if meta_path.exists():
        try:
            meta = load_json(
                meta_path
            )

            slide_path_raw = (
                meta.get(
                    "slide_path",
                    ""
                )
            )

            if slide_path_raw:
                slide_path = Path(
                    slide_path_raw
                )

                if slide_path.exists():
                    return slide_path

        except Exception:
            pass

    return find_file_by_prefix(
        str(
            row["prefix"]
        ),
        wsi_map,
    )


def validate_manifest(
    manifest: pd.DataFrame,
) -> pd.DataFrame:
    required = {
        "sample_id",
        "dataset",
        "patient_id",
        "prefix",
        "tile_idx",
        "x",
        "y",
        "patch_size",
        "pc3_score",
        "pc3_within_slide_percentile",
        "sampling_stratum",
        "coord_path",
        "pca_path",
        "meta_path",
    }

    missing = (
        required
        - set(
            manifest.columns
        )
    )

    if missing:
        raise ValueError(
            "Sampling manifest missing columns: "
            f"{sorted(missing)}"
        )

    if manifest.empty:
        raise ValueError(
            "Sampling manifest is empty."
        )

    out = manifest.copy()

    out[
        "sample_id"
    ] = out[
        "sample_id"
    ].astype(
        str
    )

    if out[
        "sample_id"
    ].duplicated().any():
        duplicates = out.loc[
            out[
                "sample_id"
            ].duplicated(
                keep=False
            ),
            "sample_id",
        ].tolist()

        raise ValueError(
            "Duplicate sample_id values: "
            f"{duplicates[:20]}"
        )

    for column in [
        "x",
        "y",
        "patch_size",
        "tile_idx",
    ]:
        out[
            column
        ] = pd.to_numeric(
            out[
                column
            ],
            errors="raise",
        ).astype(
            int
        )

    return out


def compute_context_origin(
    tile_x: int,
    tile_y: int,
    patch_size: int,
    context_size: int,
) -> Tuple[int, int]:
    tile_center_x = (
        tile_x
        + patch_size
        / 2.0
    )

    tile_center_y = (
        tile_y
        + patch_size
        / 2.0
    )

    context_x = int(
        round(
            tile_center_x
            - context_size
            / 2.0
        )
    )

    context_y = int(
        round(
            tile_center_y
            - context_size
            / 2.0
        )
    )

    return (
        context_x,
        context_y,
    )


def crop_with_white_padding(
    slide_img: Image.Image,
    x: int,
    y: int,
    width: int,
    height: int,
) -> Tuple[
    Image.Image,
    dict,
]:
    slide_width, slide_height = (
        slide_img.size
    )

    source_left = max(
        0,
        x,
    )

    source_top = max(
        0,
        y,
    )

    source_right = min(
        slide_width,
        x + width,
    )

    source_bottom = min(
        slide_height,
        y + height,
    )

    canvas = Image.new(
        "RGB",
        (
            width,
            height,
        ),
        "white",
    )

    if (
        source_right
        > source_left
        and source_bottom
        > source_top
    ):
        crop = slide_img.crop(
            (
                source_left,
                source_top,
                source_right,
                source_bottom,
            )
        ).convert(
            "RGB"
        )

        paste_x = (
            source_left
            - x
        )

        paste_y = (
            source_top
            - y
        )

        canvas.paste(
            crop,
            (
                paste_x,
                paste_y,
            ),
        )

    padding = {
        "pad_left": int(
            max(
                0,
                -x,
            )
        ),
        "pad_top": int(
            max(
                0,
                -y,
            )
        ),
        "pad_right": int(
            max(
                0,
                x + width
                - slide_width,
            )
        ),
        "pad_bottom": int(
            max(
                0,
                y + height
                - slide_height,
            )
        ),
    }

    return (
        canvas,
        padding,
    )


def draw_model_tile_box(
    context_img: Image.Image,
    tile_x: int,
    tile_y: int,
    patch_size: int,
    context_x: int,
    context_y: int,
) -> Image.Image:
    annotated = (
        context_img.copy()
    )

    draw = ImageDraw.Draw(
        annotated
    )

    local_x0 = (
        tile_x
        - context_x
    )

    local_y0 = (
        tile_y
        - context_y
    )

    local_x1 = (
        local_x0
        + patch_size
    )

    local_y1 = (
        local_y0
        + patch_size
    )

    for offset in range(
        MODEL_BOX_WIDTH
    ):
        draw.rectangle(
            [
                local_x0
                - offset,
                local_y0
                - offset,
                local_x1
                + offset,
                local_y1
                + offset,
            ],
            outline=(
                0,
                0,
                255,
            ),
        )

    return annotated


def save_png(
    image: Image.Image,
    path: Path,
) -> None:
    image.save(
        path,
        format="PNG",
        optimize=True,
    )


