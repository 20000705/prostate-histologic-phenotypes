"""
13b_extract_pc3_morphology_rois.py

Purpose
-------
Extract H&E model tiles and larger context ROIs for the frozen PC3 morphology
sampling manifest generated by step 13a.

This script performs IMAGE EXTRACTION ONLY.

It does NOT:
    - select or re-rank samples
    - change PC3 thresholds
    - change tumor definitions
    - inspect morphology
    - use pathologist review
    - compute quantitative morphology
    - use external cohorts

Input
-----
results/13a_pc3_morphology_sampling_manifest/
    pc3_sampling_manifest.csv

Required manifest columns
-------------------------
sample_id
dataset
patient_id
prefix
tile_idx
x
y
patch_size
pc3_score
pc3_within_slide_percentile
sampling_stratum
coord_path
pca_path
meta_path

Outputs
-------
results/13b_pc3_morphology_roi_extraction/

    model_tiles/
        PC3ROI_0001.png
        ...

    context_rois/
        PC3ROI_0001_context.png
        ...

    annotated_context_rois/
        PC3ROI_0001_context_with_model_box.png
        ...

    roi_extraction_manifest.csv
    failed_extractions.csv
    extraction_summary.csv
    analysis_metadata.json
    README.txt

Extraction design
-----------------
Model tile:
    exact frozen tile used for PC3 scoring
    default size = patch_size from manifest/meta (typically 224 x 224)

Context ROI:
    square ROI centered on the model tile
    default requested size = 896 x 896 pixels

Annotated context:
    same 896 x 896 context ROI with the original model tile location outlined

Boundary handling
-----------------
If the requested context ROI extends beyond the WSI boundary, the available
image region is pasted into a white canvas of the requested context size.
The model tile coordinates remain geometrically consistent.

Determinism
-----------
No random sampling is performed here. One frozen sample_id maps to one
deterministic set of extracted images.
"""

