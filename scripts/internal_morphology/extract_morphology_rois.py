def main() -> None:
    if not IN_MANIFEST.exists():
        raise FileNotFoundError(
            f"Missing sampling manifest: "
            f"{IN_MANIFEST}"
        )

    manifest = pd.read_csv(
        IN_MANIFEST
    )

    manifest = validate_manifest(
        manifest
    )

    wsi_map = build_file_map(
        WSI_DIRS
    )

    print(
        "=" * 110
    )
    print(
        "PC3 MORPHOLOGY ROI EXTRACTION"
    )
    print(
        "=" * 110
    )

    print(
        f"[INPUT MANIFEST]       "
        f"{IN_MANIFEST}"
    )

    print(
        f"[SAMPLES]              "
        f"{len(manifest)}"
    )

    print(
        f"[CONTEXT SIZE]         "
        f"{CONTEXT_SIZE}"
    )

    print(
        f"[MODEL BOX WIDTH]      "
        f"{MODEL_BOX_WIDTH}"
    )

    print(
        f"[OUTPUT]               "
        f"{OUT_DIR}"
    )

    success_rows = []
    failed_rows = []

    for index, row in manifest.iterrows():
        sample_id = str(
            row[
                "sample_id"
            ]
        )

        result, failure = extract_one_sample(
            row=row,
            wsi_map=wsi_map,
        )

        if result is not None:
            success_rows.append(
                result
            )

            if (
                index < 10
                or (
                    index + 1
                ) % 100 == 0
                or (
                    index + 1
                ) == len(
                    manifest
                )
            ):
                print(
                    f"[OK {index + 1:04d}/"
                    f"{len(manifest):04d}] "
                    f"{sample_id} | "
                    f"{row['sampling_stratum']}"
                )

        else:
            failed_rows.append(
                failure
            )

            print(
                f"[FAIL {index + 1:04d}/"
                f"{len(manifest):04d}] "
                f"{sample_id} | "
                f"{failure['reason']}"
            )

    extraction_manifest = pd.DataFrame(
        success_rows
    )

    failed = pd.DataFrame(
        failed_rows
    )

    if extraction_manifest.empty:
        raise RuntimeError(
            "No ROI extractions succeeded."
        )

    extraction_manifest = (
        extraction_manifest
        .sort_values(
            "sample_id"
        )
        .reset_index(
            drop=True
        )
    )

    extraction_manifest.to_csv(
        OUT_MANIFEST,
        index=False,
    )

    if failed.empty:
        failed = pd.DataFrame(
            columns=[
                "sample_id",
                "patient_id",
                "prefix",
                "sampling_stratum",
                "reason",
                "details",
            ]
        )

    failed.to_csv(
        OUT_FAILED,
        index=False,
    )

    summary = build_extraction_summary(
        extraction_manifest=(
            extraction_manifest
        ),
        failed=(
            failed
        ),
    )

    summary.to_csv(
        OUT_SUMMARY,
        index=False,
    )

    metadata = {
        "analysis_name": (
            "PC3 morphology ROI extraction"
        ),
        "analysis_role": (
            "Deterministic H&E extraction from frozen step-13a samples"
        ),
        "input_manifest": str(
            IN_MANIFEST
        ),
        "n_input_samples": int(
            len(
                manifest
            )
        ),
        "n_successful_extractions": int(
            len(
                extraction_manifest
            )
        ),
        "n_failed_extractions": int(
            len(
                failed
            )
        ),
        "context_size": int(
            CONTEXT_SIZE
        ),
        "save_annotated_context": bool(
            SAVE_ANNOTATED_CONTEXT
        ),
        "model_box_width": int(
            MODEL_BOX_WIDTH
        ),
        "sample_reselection_performed": False,
        "sample_reranking_performed": False,
        "morphology_used_for_extraction": False,
        "random_sampling_used": False,
        "skip_existing": bool(
            SKIP_EXISTING
        ),
        "outputs": {
            "model_tile_directory": str(
                MODEL_TILE_DIR
            ),
            "context_roi_directory": str(
                CONTEXT_DIR
            ),
            "annotated_context_directory": str(
                ANNOTATED_CONTEXT_DIR
            ),
            "roi_extraction_manifest": str(
                OUT_MANIFEST
            ),
            "failed_extractions": str(
                OUT_FAILED
            ),
            "extraction_summary": str(
                OUT_SUMMARY
            ),
            "readme": str(
                OUT_README
            ),
        },
    }

    with OUT_METADATA.open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            metadata,
            file,
            indent=2,
        )

    OUT_README.write_text(
        make_readme_text(
            summary
        ),
        encoding="utf-8",
    )

    print(
        "\n" + "=" * 110
    )

    print(
        "EXTRACTION SUMMARY"
    )

    print(
        "=" * 110
    )

    print(
        summary.to_string(
            index=False
        )
    )

    print(
        "\n[OK] Saved:"
    )

    for path in [
        OUT_MANIFEST,
        OUT_FAILED,
        OUT_SUMMARY,
        OUT_METADATA,
        OUT_README,
    ]:
        print(
            f"  {path}"
        )

    print(
        f"  {MODEL_TILE_DIR}"
    )

    print(
        f"  {CONTEXT_DIR}"
    )

    if SAVE_ANNOTATED_CONTEXT:
        print(
            f"  {ANNOTATED_CONTEXT_DIR}"
        )

    print(
        "\n[DONE] PC3 morphology ROI extraction complete."
    )


if __name__ == "__main__":
    main()
