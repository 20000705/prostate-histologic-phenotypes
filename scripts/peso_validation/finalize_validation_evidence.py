def extract_frozen_design(
    plan16a: Dict[str, Any],
):

    endpoint = plan16a.get(
        "primary_endpoint",
        {},
    )


    agg = plan16a.get(
        "aggregation_and_inference",
        {},
    )


    corrected = plan16a.get(
        "corrected_mask_sensitivity",
        {},
    )


    expected_direction = str(
        endpoint.get(
            "expected_pc3_direction",
            "",
        )
    ).strip().lower()


    if expected_direction != EXPECTED_DIRECTION:

        raise RuntimeError(
            "Frozen expected direction "
            "is not negative."
        )


    independent_unit = str(
        agg.get(
            "independent_unit",
            "",
        )
    ).strip().lower()


    if independent_unit != "slide":

        raise RuntimeError(
            "Frozen independent unit "
            "is not slide."
        )


    return {
        "target_axis":
            EXPECTED_PC_NAME,

        "expected_direction":
            expected_direction,

        "primary_endpoint":
            endpoint.get(
                "feature"
            ),

        "independent_unit":
            independent_unit,

        "slide_effect":
            agg.get(
                "continuous_slide_effect"
            ),

        "cohort_summary":
            agg.get(
                "cohort_summary"
            ),

        "confidence_interval":
            agg.get(
                "confidence_interval"
            ),

        "corrected_role":
            corrected.get(
                "role"
            ),
    }


