def validate_analysis_chain(
    meta16a: Dict[str, Any],
    meta16b: Dict[str, Any],
    meta16c: Dict[str, Any],
    meta16d: Dict[str, Any],
):

    # -------------------------------------------------------------------------
    # Step 16a
    # -------------------------------------------------------------------------

    schema16a = str(
        meta16a.get(
            "schema_version",
            "",
        )
    )


    if schema16a != EXPECTED_STEP16A_SCHEMA:

        raise RuntimeError(
            "Unexpected Step-16a schema:\n"
            f"{schema16a}"
        )


    if str(
        meta16a.get(
            "target_axis",
            "",
        )
    ).upper() != EXPECTED_PC_NAME:

        raise RuntimeError(
            "Step-16a target axis is not PC3."
        )


    if str(
        meta16a.get(
            "primary_mask_source",
            "",
        )
    ).lower().find(
        "standard"
    ) < 0:

        raise RuntimeError(
            "Step-16a primary mask source "
            "is not standard."
        )


    if bool(
        meta16a.get(
            "hybrid_primary_masking",
            True,
        )
    ):

        raise RuntimeError(
            "Step-16a indicates hybrid "
            "primary masking."
        )


    # -------------------------------------------------------------------------
    # Step 16b
    # -------------------------------------------------------------------------

    if not bool(
        meta16b.get(
            "formal_full_run",
            False,
        )
    ):

        raise RuntimeError(
            "Step-16b is not a formal full run."
        )


    if not bool(
        meta16b.get(
            "measurement_only",
            False,
        )
    ):

        raise RuntimeError(
            "Step-16b is not measurement-only."
        )


    if bool(
        meta16b.get(
            "inferential_statistics_performed",
            True,
        )
    ):

        raise RuntimeError(
            "Step-16b indicates inferential "
            "statistics were performed."
        )


    if int(
        meta16b.get(
            "n_primary_standard_slides",
            -1,
        )
    ) != EXPECTED_PRIMARY_SLIDES:

        raise RuntimeError(
            "Step-16b primary slide count "
            "is not 62."
        )


    if int(
        meta16b.get(
            "n_corrected_sensitivity_slides",
            -1,
        )
    ) != EXPECTED_CORRECTED_SLIDES:

        raise RuntimeError(
            "Step-16b corrected subset "
            "count is not 25."
        )


    # -------------------------------------------------------------------------
    # Step 16c
    # -------------------------------------------------------------------------

    if int(
        meta16c.get(
            "n_primary_slides_analyzed",
            -1,
        )
    ) != EXPECTED_PRIMARY_SLIDES:

        raise RuntimeError(
            "Step-16c primary slide count "
            "is not 62."
        )


    if int(
        meta16c.get(
            "n_corrected_slides_analyzed",
            -1,
        )
    ) != EXPECTED_CORRECTED_SLIDES:

        raise RuntimeError(
            "Step-16c corrected slide "
            "count is not 25."
        )


    if bool(
        meta16c.get(
            "tile_level_pooled_inference_performed",
            True,
        )
    ):

        raise RuntimeError(
            "Step-16c indicates pooled "
            "tile-level inference."
        )


    if bool(
        meta16c.get(
            "mask_measurement_recomputed",
            True,
        )
    ):

        raise RuntimeError(
            "Step-16c indicates mask "
            "remeasurement."
        )


    if bool(
        meta16c.get(
            "pc_axis_screening_performed",
            True,
        )
    ):

        raise RuntimeError(
            "Step-16c indicates PC-axis screening."
        )


    # -------------------------------------------------------------------------
    # Step 16d
