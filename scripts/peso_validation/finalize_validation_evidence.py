def load_json(
    path: Path,
):

    with path.open(
        "r",
        encoding="utf-8",
    ) as f:

        return json.load(
            f
        )


def write_json(
    path: Path,
    obj,
):

    with path.open(
        "w",
        encoding="utf-8",
    ) as f:

        json.dump(
            obj,
            f,
            indent=2,
            sort_keys=True,
            ensure_ascii=False,
        )


def sha256_file(
    path: Path,
) -> Optional[str]:

    if (
        not path.exists()
        or
        not path.is_file()
    ):

        return None

    h = hashlib.sha256()

    with path.open(
        "rb"
    ) as f:

        for chunk in iter(
            lambda: f.read(
                1024 * 1024
            ),
            b"",
        ):

            h.update(
                chunk
            )

    return h.hexdigest()


def finite_float(
    value,
):

    try:

        value = float(
            value
        )

    except Exception:

        return np.nan

    if not np.isfinite(
        value
    ):

        return np.nan

    return value


def bool_text(
    value: bool,
):

    return (
        "YES"
        if bool(
            value
        )
        else "NO"
    )


